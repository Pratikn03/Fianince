"""Cross-venue verification: Coinbase Pro vs Binance Spot (April 7-19, 2021).

Estimates identical VAR(1) and flow-controlled feedback models on the exact
same 12 calendar days across both venues for BTC, ETH, and ADA.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from empirical_pipeline.binance_panel import process_asset_day
from empirical_pipeline.feedback_var import run as run_coinbase

PROV = ROOT / "results" / "provenance"
GEN = ROOT / "paper" / "generated"

DATES = [f"2021-04-{d:02d}" for d in range(8, 19)]  # 11 full calendar days common to both
SYMS = {"BTC": "BTCUSDT", "ETH": "ETHUSDT", "ADA": "ADAUSDT"}


def run_cross_venue():
    # 1. Load Coinbase results
    cb_path = PROV / "empirical_feedback.json"
    if not cb_path.exists():
        run_coinbase()
    cb = json.loads(cb_path.read_text())["baseline"]

    # 2. Run Binance for matching dates
    binance_res = {a: [] for a in SYMS}
    for asset, sym in SYMS.items():
        print(f"Running Binance {sym} for April 2021 dates...")
        for d in DATES:
            r = process_asset_day(sym, d)
            if r is not None:
                binance_res[asset].append(r)

    out = {}
    for asset in SYMS:
        cb_a = cb[asset]["summary"]
        bn_list = binance_res[asset]
        b_df = pd.DataFrame(bn_list)
        out[asset] = {
            "coinbase": {
                "days": cb_a["S"]["n_days"],
                "Q": cb_a["Q"]["mean"],
                "Q_ci": cb_a["Q"]["ci95"],
                "S": cb_a["S"]["mean"],
                "S_ci": cb_a["S"]["ci95"],
                "L": cb_a["L"]["mean"],
                "L_ci": cb_a["L"]["ci95"],
            },
            "binance": {
                "days": len(b_df),
                "Q": float(b_df["Q"].mean()),
                "Q_ci": [float(b_df["Q"].mean() - 1.96 * b_df["Q"].sem()), float(b_df["Q"].mean() + 1.96 * b_df["Q"].sem())],
                "S": float(b_df["S"].mean()),
                "S_ci": [float(b_df["S"].mean() - 1.96 * b_df["S"].sem()), float(b_df["S"].mean() + 1.96 * b_df["S"].sem())],
                "L": float(b_df["L"].mean()),
                "L_ci": [float(b_df["L"].mean() - 1.96 * b_df["L"].sem()), float(b_df["L"].mean() + 1.96 * b_df["L"].sem())],
            }
        }

    sum_path = PROV / "cross_venue_summary.json"
    with open(sum_path, "w") as f:
        json.dump(out, f, indent=1)
    print(f"Saved cross-venue summary to {sum_path}")

    # Generate LaTeX Table
    lines = [
        "% AUTO-GENERATED by empirical_pipeline/cross_venue_check.py. Do not edit.",
        r"\begin{tabular}{llrrrrr}\toprule",
        r"Asset & Venue & Days & $\hat Q$ [95\% CI] & $\hat S$ [95\% CI] & $\hat{\mathcal L}$ [95\% CI]\\\midrule",
    ]
    for asset in ["BTC", "ETH", "ADA"]:
        c = out[asset]["coinbase"]
        b = out[asset]["binance"]
        lines.append(
            f"{asset} & Coinbase Pro & {c['days']} & ${c['Q']:.4f}$ [${c['Q_ci'][0]:.4f}, {c['Q_ci'][1]:.4f}$] & "
            f"${c['S']:.3f}$ [${c['S_ci'][0]:.3f}, {c['S_ci'][1]:.3f}$] & ${c['L']:.3f}$ [${c['L_ci'][0]:.3f}, {c['L_ci'][1]:.3f}$]\\\\"
        )
        lines.append(
            f" & Binance Spot & {b['days']} & ${b['Q']:.4f}$ [${b['Q_ci'][0]:.4f}, {b['Q_ci'][1]:.4f}$] & "
            f"${b['S']:.3f}$ [${b['S_ci'][0]:.3f}, {b['S_ci'][1]:.3f}$] & ${b['L']:.3f}$ [${b['L_ci'][0]:.3f}, {b['L_ci'][1]:.3f}$]\\\\"
        )
        if asset != "ADA":
            lines.append(r"\addlinespace")
    lines.append(r"\bottomrule\end{tabular}")
    (GEN / "cross_venue_comparison.tex").write_text("\n".join(lines) + "\n")
    print("Generated cross_venue_comparison.tex successfully.")


if __name__ == "__main__":
    run_cross_venue()
