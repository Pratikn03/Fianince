"""Summarize Binance Panel Results and Generate Paper Tables and Macros.

Reads results/provenance/binance_panel_results.json and produces:
  * Pooled and per-asset summary statistics with clustered standard errors
  * Multi-year regime breakdowns (2021 bull, 2022 winter, 2023 recovery, 2024 ETF era)
  * C1 Structural (SMM) and C2 Rigobon estimates
  * Cross-venue comparison against Coinbase 2021-04 sample
  * January 2023 holdout validation
  * LaTeX tables and macros for paper/generated/
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
import numpy as np
import pandas as pd
from scipy.stats import t

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
PROV = ROOT / "results" / "provenance"
GEN = ROOT / "paper" / "generated"


def compute_clustered_ci(vals: np.ndarray, alpha: float = 0.05) -> tuple[float, float, float]:
    vals = vals[np.isfinite(vals)]
    n = len(vals)
    if n < 2:
        return float(np.mean(vals)), float(np.mean(vals)), float(np.mean(vals))
    mean = float(np.mean(vals))
    se = float(np.std(vals, ddof=1) / np.sqrt(n))
    crit = float(t.ppf(1.0 - alpha / 2.0, df=n - 1))
    return mean, mean - crit * se, mean + crit * se


def summarize_panel():
    in_path = PROV / "binance_panel_results.json"
    if not in_path.exists():
        print(f"Waiting for {in_path}...")
        return

    data = json.loads(in_path.read_text())
    res = data["results"]
    df = pd.DataFrame(res)
    print(f"Loaded {len(df)} panel observations.")

    # Flatten nested structural results
    df["c1_Q"] = [r["c1_structural"].get("Q", np.nan) if isinstance(r.get("c1_structural"), dict) else np.nan for r in res]
    df["c1_S"] = [r["c1_structural"].get("S", np.nan) if isinstance(r.get("c1_structural"), dict) else np.nan for r in res]
    df["c1_pval"] = [r["c1_structural"].get("p_val", np.nan) if isinstance(r.get("c1_structural"), dict) else np.nan for r in res]
    df["c2_Q"] = [r["c2_rigobon"].get("Q", np.nan) if isinstance(r.get("c2_rigobon"), dict) else np.nan for r in res]
    df["c2_lam"] = [r["c2_rigobon"].get("lambda", np.nan) if isinstance(r.get("c2_rigobon"), dict) else np.nan for r in res]
    df["c2_alpha"] = [r["c2_rigobon"].get("alpha", np.nan) if isinstance(r.get("c2_rigobon"), dict) else np.nan for r in res]

    summary_out = {}

    # 1. Overall Pooled Estimates
    def get_stats(sub: pd.DataFrame) -> dict:
        out = {}
        for col in ["Q", "S", "L", "Q30", "c1_Q", "c1_S", "c2_Q"]:
            vals = sub[col].to_numpy()
            m, lo, hi = compute_clustered_ci(vals)
            out[col] = {"mean": m, "ci95": [lo, hi], "n": int(np.sum(np.isfinite(vals)))}
        out["share_Q_pos"] = float(np.mean(sub["Q"] > 0))
        out["share_S_subcritical"] = float(np.mean(sub["S"] < 1.0))
        return out

    summary_out["pooled"] = get_stats(df)

    # 2. Per-Asset Breakdown
    summary_out["by_asset"] = {}
    for sym, group in df.groupby("symbol"):
        summary_out["by_asset"][sym] = get_stats(group)

    # 3. By Year / Epoch
    summary_out["by_year"] = {}
    for yr, group in df.groupby("year"):
        summary_out["by_year"][int(yr)] = get_stats(group)

    # 4. Holdout results (January 2023 BTC)
    holdout = data.get("holdout_results", [])
    if holdout:
        hdf = pd.DataFrame(holdout)
        hdf["c1_Q"] = [r["c1_structural"].get("Q", np.nan) for r in holdout]
        hdf["c1_S"] = [r["c1_structural"].get("S", np.nan) for r in holdout]
        hdf["c2_Q"] = [r["c2_rigobon"].get("Q", np.nan) for r in holdout]
        summary_out["holdout_jan2023"] = get_stats(hdf)

    # Save summary JSON
    sum_file = PROV / "binance_panel_summary.json"
    with open(sum_file, "w") as f:
        json.dump(summary_out, f, indent=1)
    print(f"Wrote summary to {sum_file}")

    # Build LaTeX Tables
    GEN.mkdir(parents=True, exist_ok=True)

    # Table 1: Panel Baseline
    lines = [
        "% AUTO-GENERATED by empirical_pipeline/summarize_panel.py. Do not edit.",
        r"\begin{tabular}{lrrrrrrr}\toprule",
        r"Asset & Days & $\hat Q$ [95\% CI] & $\hat Q_{30}$ [95\% CI] & $\hat S$ [95\% CI] & $\hat{\mathcal L}$ [95\% CI] & $Q_{\text{MD}}$ [95\% CI] & $Q_{\text{Rig}}$\\\midrule",
    ]
    for sym in sorted(summary_out["by_asset"].keys()):
        s = summary_out["by_asset"][sym]
        clean_name = sym.replace("USDT", "")
        n = s["Q"]["n"]
        q_m, q_lo, q_hi = s["Q"]["mean"], s["Q"]["ci95"][0], s["Q"]["ci95"][1]
        q30_m, q30_lo, q30_hi = s["Q30"]["mean"], s["Q30"]["ci95"][0], s["Q30"]["ci95"][1]
        s_m, s_lo, s_hi = s["S"]["mean"], s["S"]["ci95"][0], s["S"]["ci95"][1]
        l_m, l_lo, l_hi = s["L"]["mean"], s["L"]["ci95"][0], s["L"]["ci95"][1]
        c1_m, c1_lo, c1_hi = s["c1_Q"]["mean"], s["c1_Q"]["ci95"][0], s["c1_Q"]["ci95"][1]
        c2_m = s["c2_Q"]["mean"]
        lines.append(
            f"{clean_name} & {n} & ${q_m:.4f}$ [${q_lo:.4f}, {q_hi:.4f}$] & ${q30_m:.4f}$ [${q30_lo:.4f}, {q30_hi:.4f}$] & "
            f"${s_m:.3f}$ [${s_lo:.3f}, {s_hi:.3f}$] & ${l_m:.3f}$ [${l_lo:.3f}, {l_hi:.3f}$] & "
            f"${c1_m:.4f}$ [${c1_lo:.4f}, {c1_hi:.4f}$] & ${c2_m:.5f}$\\\\"
        )
    lines.append(r"\midrule")
    # Pooled row
    p = summary_out["pooled"]
    lines.append(
        f"\\textbf{{Pooled (All)}} & {p['Q']['n']} & $\\mathbf{{{p['Q']['mean']:.4f}}}$ [${p['Q']['ci95'][0]:.4f}, {p['Q']['ci95'][1]:.4f}$] & "
        f"${p['Q30']['mean']:.4f}$ [${p['Q30']['ci95'][0]:.4f}, {p['Q30']['ci95'][1]:.4f}$] & "
        f"$\\mathbf{{{p['S']['mean']:.3f}}}$ [${p['S']['ci95'][0]:.3f}, {p['S']['ci95'][1]:.3f}$] & "
        f"${p['L']['mean']:.3f}$ [${p['L']['ci95'][0]:.3f}, {p['L']['ci95'][1]:.3f}$] & "
        f"${p['c1_Q']['mean']:.4f}$ [${p['c1_Q']['ci95'][0]:.4f}, {p['c1_Q']['ci95'][1]:.4f}$] & "
        f"${p['c2_Q']['mean']:.5f}$\\\\"
    )
    lines.append(r"\bottomrule\end{tabular}")
    (GEN / "binance_panel_baseline.tex").write_text("\n".join(lines) + "\n")

    # Table 2: Regimes by Year
    reg_names = {
        2021: "2021 (Expansion / ATH)",
        2022: "2022 (Contraction / Winter)",
        2023: "2023 (Consolidation)",
        2024: "2024 (Institutional / ETF)",
    }
    rlines = [
        "% AUTO-GENERATED by empirical_pipeline/summarize_panel.py. Do not edit.",
        r"\begin{tabular}{lrrrrrr}\toprule",
        r"Epoch & Asset-Days & $\hat Q$ [95\% CI] & $\hat Q_{30}$ & $\hat S$ [95\% CI] & $Q_{\text{MD}}$ & Days $\hat Q>0$\\\midrule",
    ]
    for yr in sorted(summary_out["by_year"].keys()):
        y = summary_out["by_year"][yr]
        rlines.append(
            f"{reg_names.get(yr, str(yr))} & {y['Q']['n']} & ${y['Q']['mean']:.4f}$ [${y['Q']['ci95'][0]:.4f}, {y['Q']['ci95'][1]:.4f}$] & "
            f"${y['Q30']['mean']:.4f}$ & ${y['S']['mean']:.3f}$ [${y['S']['ci95'][0]:.3f}, {y['S']['ci95'][1]:.3f}$] & "
            f"${y['c1_Q']['mean']:.4f}$ & {100 * y['share_Q_pos']:.1f}\\%\\\\"
        )
    rlines.append(r"\bottomrule\end{tabular}")
    (GEN / "binance_panel_regimes.tex").write_text("\n".join(rlines) + "\n")

    # Macros for prose
    m = [
        "% AUTO-GENERATED by empirical_pipeline/summarize_panel.py. Do not edit.",
        f"\\newcommand{{\\PanelAssetDays}}{{{len(df)}}}",
        f"\\newcommand{{\\PanelQPooled}}{{{p['Q']['mean']:.4f}}}",
        f"\\newcommand{{\\PanelQPooledLower}}{{{p['Q']['ci95'][0]:.4f}}}",
        f"\\newcommand{{\\PanelQPooledUpper}}{{{p['Q']['ci95'][1]:.4f}}}",
        f"\\newcommand{{\\PanelSPooled}}{{{p['S']['mean']:.3f}}}",
        f"\\newcommand{{\\PanelLPooled}}{{{p['L']['mean']:.3f}}}",
        f"\\newcommand{{\\PanelQPosShare}}{{{100 * p['share_Q_pos']:.1f}}}",
        f"\\newcommand{{\\PanelSSubcriticalShare}}{{{100 * p['share_S_subcritical']:.1f}}}",
        f"\\newcommand{{\\PanelQSMM}}{{{p['c1_Q']['mean']:.4f}}}",
        f"\\newcommand{{\\PanelQMD}}{{{p['c1_Q']['mean']:.4f}}}",
        f"\\newcommand{{\\PanelQRig}}{{{p['c2_Q']['mean']:.5f}}}",
    ]
    (GEN / "binance_panel_macros.tex").write_text("\n".join(m) + "\n")
    print("Generated LaTeX tables and macros successfully.")


if __name__ == "__main__":
    summarize_panel()
