"""Flow Sign-Memory Estimation and Identified Sets (Phase D).

1. Estimates empirical power-law exponent gamma:
      Corr(sgn(f_t), sgn(f_{t+k})) ~ C * k^(-gamma)
   for lags k = 1 to 100.
2. Characterizes the decomposition between mechanical order-splitting bias
   and genuine price-responsive feedback.
3. Computes the identified set [Q_min, Q_max] robust to hidden slow learning cohorts
   and long-memory order flow.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from empirical_pipeline.feedback_var import load_asset, build_series, var1, q_long_memory_robust

PROV = ROOT / "results" / "provenance"
GEN = ROOT / "paper" / "generated"


def estimate_sign_memory_gamma(flow: np.ndarray, max_lag: int = 100) -> dict:
    s = np.sign(flow)
    s = s[s != 0]
    n = len(s)
    lags = np.arange(1, min(max_lag + 1, n // 10))
    autocorr = []
    for k in lags:
        c = np.corrcoef(s[:-k], s[k:])[0, 1]
        autocorr.append(max(1e-6, float(c)))
    autocorr = np.array(autocorr)

    # Power law: log(autocorr) = log(C) - gamma * log(k)
    log_k = np.log(lags)
    log_c = np.log(autocorr)
    fit_mask = (lags >= 5) & (lags <= 60)
    slope, intercept = np.polyfit(log_k[fit_mask], log_c[fit_mask], 1)
    gamma = -float(slope)
    return {
        "gamma": float(gamma),
        "c_constant": float(np.exp(intercept)),
        "lags": lags.tolist()[:20],
        "autocorr": autocorr.tolist()[:20],
    }


def compute_identified_set(asset: str) -> dict:
    df = load_asset(asset)
    gamma_res = estimate_sign_memory_gamma(df["flow"].to_numpy())

    series = build_series(df, delta=10, window=300)
    x = series["x"].to_numpy()
    f = series["f"].to_numpy()

    v = var1(x, f)
    q_raw = float(v["Q"])
    q_30 = float(q_long_memory_robust(x, f, 30)["Q_L"])
    q_90 = float(q_long_memory_robust(x, f, 90)["Q_L"])

    # Identified set bounds:
    # Lower bound: Q_90 (fully purge order-splitting up to 15 minutes)
    # Upper bound: Q_raw * 1.5 (allowing for slow-cohort attenuation by Theorem M1 / Jensen bound)
    q_min = float(max(0.001, q_90))
    q_max = float(q_raw * 1.5)
    l_max = float(q_max / (1.0 - v["J11"]))

    return {
        "asset": asset,
        "gamma": gamma_res["gamma"],
        "c_constant": gamma_res["c_constant"],
        "Q_raw": q_raw,
        "Q_30": q_30,
        "Q_90": q_90,
        "identified_set": [q_min, q_max],
        "L_max": l_max,
        "S_max": float(v["J11"] + q_max),
    }


def run_bias_analysis():
    results = {}
    for asset in ["BTC", "ETH", "ADA"]:
        print(f"Analyzing flow sign memory and identified set for {asset}...")
        results[asset] = compute_identified_set(asset)

    out_file = PROV / "flow_memory_bias_correction.json"
    with open(out_file, "w") as f:
        json.dump(results, f, indent=1)
    print(f"Saved identified set analysis to {out_file}")

    # Generate LaTeX Table
    lines = [
        "% AUTO-GENERATED by empirical_pipeline/flow_memory_and_bias_correction.py. Do not edit.",
        r"\begin{tabular}{lrrrrrr}\toprule",
        r"Asset & $\gamma$ (sign memory) & $\hat Q$ (VAR1) & $\hat Q_{30}$ & $\hat Q_{90}$ & Identified Set $[Q_{\min}, Q_{\max}]$ & Max $\mathcal L$\\\midrule",
    ]
    for asset in ["BTC", "ETH", "ADA"]:
        r = results[asset]
        lines.append(
            f"{asset} & ${r['gamma']:.3f}$ & ${r['Q_raw']:.4f}$ & ${r['Q_30']:.4f}$ & ${r['Q_90']:.4f}$ & "
            f"[${r['identified_set'][0]:.4f}, {r['identified_set'][1]:.4f}$] & ${r['L_max']:.3f}$\\\\"
        )
    lines.append(r"\bottomrule\end{tabular}")
    (GEN / "flow_memory_bias_table.tex").write_text("\n".join(lines) + "\n")
    print("Generated flow_memory_bias_table.tex successfully.")


if __name__ == "__main__":
    run_bias_analysis()
