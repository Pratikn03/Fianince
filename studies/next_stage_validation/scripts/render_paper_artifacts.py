#!/usr/bin/env python3
"""Regenerate LaTeX macros and figures from saved next-stage JSON outputs."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=Path(__file__).resolve().parents[1] / "results")
    parser.add_argument("--paper", type=Path, default=Path(__file__).resolve().parents[3] / "paper")
    args = parser.parse_args()
    results = args.results.resolve()
    paper = args.paper.resolve()
    paper.mkdir(parents=True, exist_ok=True)

    agent = json.loads((results / "matched_agent_analysis.json").read_text())
    observations = json.loads((results / "observation_benchmark.json").read_text())
    interventions = json.loads((results / "intervention_results.json").read_text())["results"]["policies"]
    calibration = json.loads((results / "kline_calibration_summary.json").read_text())["assets"]
    l2 = json.loads((results / "l2_calibration_results.json").read_text())

    agent_rows = agent["summaries"]
    mean_neural_minus_adaptive = float(np.mean([
        row["paired_neural_minus_adaptive"]["mean"] for row in agent_rows
    ]))
    macros = [
        "% Auto-generated by studies/next_stage_validation/scripts/render_paper_artifacts.py",
        f"\\newcommand{{\\AgentSeedCount}}{{{len(agent_rows)}}}",
        f"\\newcommand{{\\AgentEpisodes}}{{{agent_rows[0]['episodes']}}}",
        f"\\newcommand{{\\MeanNeuralAdaptive}}{{{mean_neural_minus_adaptive:.3f}}}",
        f"\\newcommand{{\\ObsConstrainedCoverage}}{{{observations['conditions']['constrained_noisy_dependent']['coverage']:.3f}}}",
        f"\\newcommand{{\\ObsConstrainedWrong}}{{{observations['conditions']['constrained_noisy_dependent']['wrong_confident_fraction']:.3f}}}",
        f"\\newcommand{{\\ObsConstrainedUnresolved}}{{{observations['conditions']['constrained_noisy_dependent']['unresolved_fraction']:.3f}}}",
        f"\\newcommand{{\\InterventionNoneRate}}{{{interventions['none']['event_rate']:.3f}}}",
        f"\\newcommand{{\\InterventionThrottleRate}}{{{interventions['throttle']['event_rate']:.3f}}}",
        f"\\newcommand{{\\InterventionThrottleDrawdown}}{{{interventions['throttle']['mean_max_drawdown']:.3f}}}",
        "\\newcommand{\\AgentResultsTable}{%",
        "\\begin{tabular}{lrrrr}",
        "Seed & No trade & Adaptive & Neural & Neural - adaptive\\\\\\hline",
    ]
    for row in agent_rows:
        gains = row["mean_gain"]
        delta = row["paired_neural_minus_adaptive"]["mean"]
        macros.append(
            f"{row['training_seed']} & {gains['fixed_rule']:.3f} & {gains['adaptive_linear']:.3f} & {gains['frozen_neural']:.3f} & {delta:.3f}\\\\"
        )
    macros += [
        "\\end{tabular}%",
        "}",
        "\\newcommand{\\ObservationResultsTable}{%",
        "\\begin{tabular}{lrrrr}",
        "Condition & Coverage & Decisive & Wrong confident & Unresolved\\\\\\hline",
    ]
    for name, row in observations["conditions"].items():
        latex_name = name.replace("_", chr(92) + "_")
        macros.append(
            f"{latex_name} & {row['coverage']:.3f} & {row['decisive_fraction']:.3f} & {row['wrong_confident_fraction']:.3f} & {row['unresolved_fraction']:.3f}\\\\"
        )
    macros += ["\\end{tabular}%", "}", "\\newcommand{\\InterventionResultsTable}{%", "\\begin{tabular}{lrrr}", "Policy & Event rate & Gain & Drawdown\\\\\\hline"]
    for name, row in interventions.items():
        macros.append(f"{name} & {row['event_rate']:.3f} & {row['mean_gain']:.3f} & {row['mean_max_drawdown']:.3f}\\\\")
    macros += ["\\end{tabular}%", "}", "\\newcommand{\\CalibrationResultsTable}{%", "\\begin{tabular}{lrrrr}", "Asset & Train & Validation & Test & Return volatility\\\\\\hline"]
    for name, row in calibration.items():
        summary = row["summary"]
        latex_name = name.replace("_", chr(92) + "_")
        macros.append(
            f"{latex_name} & {summary['rows']['train']} & {summary['rows']['validation']} & {summary['rows']['test']} & {summary['targets']['close_return_volatility']:.5f}\\\\"
        )
    macros += ["\\end{tabular}%", "}", "\\newcommand{\\LTwoCalibrationTable}{%", "\\begin{tabular}{lrrrrr}", "Symbol & Test days & Snapshots/day & Trades & Flow ACF & Return vol.\\\\\\hline"]
    for name, row in l2["symbols_results"].items():
        test = row["splits"]["test"]
        macros.append(
            f"{name} & {test['days']} & {test['depth']['snapshot_count']:.0f} & {test['trades']['trade_count']:.0f} & {test['trades']['order_flow_sign_autocorrelation']:.3f} & {test['trades']['trade_return_volatility_proxy']:.5f}\\\\"
        )
    macros += ["\\end{tabular}%", "}"]
    _write(paper / "generated_results.tex", "\n".join(macros) + "\n")

    names = [str(row["training_seed"]) for row in agent_rows]
    x = np.arange(len(names))
    width = 0.25
    fig, ax = plt.subplots(figsize=(7.0, 3.8))
    for offset, key, label in [(-width, "adaptive_linear", "Adaptive"), (0, "frozen_neural", "Frozen neural"), (width, "fixed_rule", "No trade")]:
        values = [row["mean_gain"][key] for row in agent_rows]
        ax.bar(x + offset, values, width, label=label)
    ax.axhline(0, color="black", linewidth=0.7)
    ax.set_xticks(x, names)
    ax.set_ylabel("Mean gain")
    ax.set_xlabel("Training seed")
    ax.legend(frameon=False, ncols=3)
    fig.tight_layout()
    fig.savefig(paper / "next_stage_agent_gains.png", dpi=180)
    plt.close(fig)

    condition_names = list(observations["conditions"])
    fig, ax = plt.subplots(figsize=(8.0, 3.8))
    ax.bar(np.arange(len(condition_names)), [observations["conditions"][n]["coverage"] for n in condition_names], label="Coverage")
    ax.bar(np.arange(len(condition_names)), [observations["conditions"][n]["unresolved_fraction"] for n in condition_names], bottom=[observations["conditions"][n]["coverage"] for n in condition_names], label="Unresolved")
    short_names = [
        "Exact" + chr(10) + "independent",
        "Noisy" + chr(10) + "independent",
        "Noisy" + chr(10) + "dependent",
        "Noisy +" + chr(10) + "missing",
        "Constrained" + chr(10) + "noisy + dependent",
    ]
    ax.set_xticks(np.arange(len(condition_names)), short_names, rotation=0, fontsize=8)
    ax.set_ylim(0, 2.0)
    ax.set_ylabel("Fraction (stacked diagnostic)")
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(paper / "next_stage_observation_diagnostics.png", dpi=180)
    plt.close(fig)

    policy_names = list(interventions)
    fig, ax = plt.subplots(figsize=(6.5, 3.8))
    ax.bar(np.arange(len(policy_names)), [interventions[n]["event_rate"] for n in policy_names], color=["#777777", "#2a6fbb", "#bb6f2a"])
    ax.set_xticks(np.arange(len(policy_names)), policy_names)
    ax.set_ylim(0, 1)
    ax.set_ylabel("Nonterminal event rate")
    fig.tight_layout()
    fig.savefig(paper / "next_stage_intervention_events.png", dpi=180)
    plt.close(fig)
    print(f"wrote paper assets to {paper}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
