"""Build every paper table that depends on computed results.

Each builder reads a JSON produced by code (never typed numbers) and writes a
LaTeX fragment to paper/generated/, which the manuscript \\input{}s.
Run:  /opt/homebrew/bin/python3.11 scripts/build_results.py [--recompute]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
GEN = ROOT / "paper" / "generated"
PROV = ROOT / "results" / "provenance"


def _fmt(v, nd):
    out = f"{v:.{nd}f}"
    return out[1:] if out.startswith("-") and float(out) == 0 else out


def _ci(s, nd=4):
    return f"${_fmt(s['mean'], nd)}$ [{_fmt(s['ci95'][0], nd)}, {_fmt(s['ci95'][1], nd)}]"


def _header(src):
    return f"% AUTO-GENERATED by scripts/build_results.py from {src}. Do not edit.\n"


# --------------------------------------------------------------------------
def build_empirical(recompute: bool) -> None:
    path = PROV / "empirical_feedback.json"
    if recompute or not path.exists():
        from empirical_pipeline.feedback_var import run

        run()
    r = json.loads(path.read_text())

    # Table: baseline
    lines = [_header("results/provenance/empirical_feedback.json"),
             r"\begin{tabular}{lrlrlllll}\toprule",
             r"Asset & Days & $\hat a$ [95\% CI] & $a_0$ & $\hat Q$ [95\% CI] & $\hat Q_{30}$ [95\% CI] & $\hat{\mathcal L}$ [95\% CI] & $\hat S$ [95\% CI] & Placebo $\hat Q$\\\midrule"]
    for a, v in r["baseline"].items():
        s = v["summary"]
        lines.append(
            f"{a} & {s['S']['n_days']} & {_ci(s['a'])} & {s['a0_martingale_benchmark']:.4f} & "
            f"{_ci(s['Q'])} & {_ci(v['Q_long_memory_robust']['L30'])} & {_ci(s['L'], 3)} & {_ci(s['S'])} & ${_fmt(s['placebo_Q']['mean'], 4)}$\\\\")
    lines += [r"\bottomrule\end{tabular}"]
    (GEN / "empirical_feedback_baseline.tex").write_text("\n".join(lines) + "\n")

    # Table: c robustness to flow long memory
    lines = [_header("results/provenance/empirical_feedback.json"),
             r"\begin{tabular}{lrrrr}\toprule",
             r"Asset & $\hat c$ (1 flow lag) & $\hat c$ (30 lags) & $\hat c$ (90 lags) & ratio 90/1\\\midrule"]
    for a, v in r["baseline"].items():
        c = v["c_flow_lag_controlled"]
        lines.append(f"{a} & {c['L1']['mean']:.1f} ($t={c['L1']['t']:.1f}$) & {c['L30']['mean']:.1f} ($t={c['L30']['t']:.1f}$) & "
                     f"{c['L90']['mean']:.1f} ($t={c['L90']['t']:.1f}$) & {c['L90']['mean'] / c['L1']['mean']:.2f}\\\\")
    lines += [r"\bottomrule\end{tabular}"]
    (GEN / "empirical_feedback_flowmemory.tex").write_text("\n".join(lines) + "\n")

    # Table: sensitivity grid
    lines = [_header("results/provenance/empirical_feedback.json"),
             r"\begin{tabular}{lrrrlllr}\toprule",
             r"Asset & $\Delta$ (s) & $W$ (s) & $a_0$ & $\hat S$ [95\% CI] & $\hat Q$ [95\% CI] & $\hat{\mathcal L}$ [95\% CI] & Days $\hat Q>0$\\\midrule"]
    for g in r["grid"]:
        lines.append(f"{g['asset']} & {g['delta_s']} & {g['window_s']} & {g['a0_martingale_benchmark']:.4f} & "
                     f"{_ci(g['S'])} & {_ci(g['Q'])} & {_ci(g['L'], 3)} & {100 * g['share_days_Q_pos']:.0f}\\%\\\\")
    lines += [r"\bottomrule\end{tabular}"]
    (GEN / "empirical_feedback_grid.tex").write_text("\n".join(lines) + "\n")

    # Table: kernel + CM-cone test
    lines = [_header("results/provenance/empirical_feedback.json"),
             r"\begin{tabular}{lrrrrrrr}\toprule",
             r"Asset & $\hat b_0$ & $\hat b_1$ & $\hat b_2$ & $\hat b_3$ & $\hat b_4$ & CM test on $\hat b$: $T$ ($p$) & on $-\hat b$: $T$ ($p$)\\\midrule"]
    for a, k in r["kernel"].items():
        b, se = k["k_hat_per_sd_flow"], k["se_hac"]
        cells = " & ".join(f"${b[j]:.4f}$ \\scriptsize({se[j]:.4f})" for j in range(5))
        tp, tn = k["cm_test_k"], k["cm_test_minus_k"]
        lines.append(f"{a} & {cells} & {tp['T']:.1f} ({tp['p_value']:.3f}) & {tn['T']:.1f} ({tn['p_value']:.4f})\\\\")
    lines += [r"\bottomrule\end{tabular}"]
    (GEN / "empirical_kernel_cm.tex").write_text("\n".join(lines) + "\n")

    # Macros for prose
    b = r["baseline"]
    q = [b[a]["summary"]["Q"] for a in b]
    s = [b[a]["summary"]["S"] for a in b]
    rho = [b[a]["summary"]["rho"] for a in b]
    Ls = [b[a]["summary"]["L"] for a in b]
    gridL = [g["L"]["mean"] for g in r["grid"]]
    grid_S_max = max(g["S"]["ci95"][1] for g in r["grid"])
    grid_Q_pos = all(g["Q"]["ci95"][0] > 0 for g in r["grid"])
    pk = {a: r["kernel"][a]["cm_test_k"]["p_value"] for a in r["kernel"]}
    qr = [b[a]["Q_long_memory_robust"]["L30"] for a in b]
    red = [1 - b[a]["Q_long_memory_robust"]["L30"]["mean"] / b[a]["summary"]["Q"]["mean"] for a in b]
    crat = [b[a]["c_flow_lag_controlled"]["L90"]["mean"] / b[a]["c_flow_lag_controlled"]["L1"]["mean"] for a in b]
    macros_extra = [f"\\newcommand{{\\EmpQrobRedMin}}{{{100 * min(red):.0f}}}",
                    f"\\newcommand{{\\EmpQrobRedMax}}{{{100 * max(red):.0f}}}",
                    f"\\newcommand{{\\EmpCratioMin}}{{{100 * min(crat):.0f}}}",
                    f"\\newcommand{{\\EmpCratioMax}}{{{100 * max(crat):.0f}}}",f"\\newcommand{{\\EmpQrobMin}}{{{min(x['mean'] for x in qr):.4f}}}",
                    f"\\newcommand{{\\EmpQrobMax}}{{{max(x['mean'] for x in qr):.4f}}}",
                    f"\\newcommand{{\\EmpQrobAllPos}}{{{'all' if all(x['ci95'][0] > 0 for x in qr) else 'not all'}}}"]
    macros = [_header("results/provenance/empirical_feedback.json"),
              f"\\newcommand{{\\EmpQmin}}{{{min(x['mean'] for x in q):.4f}}}",
              f"\\newcommand{{\\EmpQmax}}{{{max(x['mean'] for x in q):.4f}}}",
              f"\\newcommand{{\\EmpSmin}}{{{min(x['mean'] for x in s):.3f}}}",
              f"\\newcommand{{\\EmpSmax}}{{{max(x['mean'] for x in s):.3f}}}",
              f"\\newcommand{{\\EmpLmin}}{{{min(x['mean'] for x in Ls):.3f}}}",
              f"\\newcommand{{\\EmpLmax}}{{{max(x['mean'] for x in Ls):.3f}}}",
              f"\\newcommand{{\\EmpGridLmin}}{{{min(gridL):.3f}}}",
              f"\\newcommand{{\\EmpGridLmax}}{{{max(gridL):.3f}}}",
              f"\\newcommand{{\\EmpRhoMax}}{{{max(x['mean'] for x in rho):.3f}}}",
              f"\\newcommand{{\\EmpGridSmaxUpper}}{{{grid_S_max:.4f}}}",
              f"\\newcommand{{\\EmpGridQallPositive}}{{{'all' if grid_Q_pos else 'not all'}}}",
              f"\\newcommand{{\\EmpCMpBTC}}{{{pk.get('BTC', float('nan')):.3f}}}",
              f"\\newcommand{{\\EmpCMpETH}}{{{pk.get('ETH', float('nan')):.3f}}}",
              f"\\newcommand{{\\EmpCMpADA}}{{{pk.get('ADA', float('nan')):.3f}}}"] + macros_extra
    (GEN / "empirical_macros.tex").write_text("\n".join(macros) + "\n")


def build_validation(recompute: bool) -> None:
    path = PROV / "estimator_validation.json"
    if recompute or not path.exists():
        from simulations.estimator_validation import run

        run()
    r = json.loads(path.read_text())
    names = {"G0": "G0: no feedback, long-memory flow", "G1": "G1: one cohort",
             "G2": "G2: two cohorts (fast + slow)", "G3": "G3: one cohort + long-memory flow"}
    lines = [_header("results/provenance/estimator_validation.json"),
             r"\begin{tabular}{lrrrrr}\toprule",
             r"DGP & $Q$ (true) & $\hat Q$ VAR(1) & $\hat Q_{30}$ & $\hat Q_{90}$ & $\hat c_{90}/\hat c_{1}$\\\midrule"]
    for k, v in r["dgps"].items():
        lines.append(f"{names[k]} & {v['Q_true']:.4f} & {v['Q_mean']:.4f} ({v['Q_sd']:.4f}) & "
                     f"{_fmt(v['Q_L30_mean'], 4)} ({v['Q_L30_sd']:.4f}) & {_fmt(v['Q_L90_mean'], 4)} ({v['Q_L90_sd']:.4f}) & "
                     f"{_fmt(v['c_ratio_90_1'], 2)}\\\\")
    lines += [r"\bottomrule\end{tabular}"]
    (GEN / "estimator_validation.tex").write_text("\n".join(lines) + "\n")
    m = [_header("results/provenance/estimator_validation.json"),
         f"\\newcommand{{\\ValReps}}{{{r['n_rep']}}}",
         f"\\newcommand{{\\ValGzeroQ}}{{{r['dgps']['G0']['Q_mean']:.4f}}}",
         f"\\newcommand{{\\ValGthreeBias}}{{{100 * r['dgps']['G3']['Q_bias_rel']:.0f}}}",
         f"\\newcommand{{\\ValGtwoBias}}{{{-100 * r['dgps']['G2']['Q_bias_rel']:.0f}}}",
         f"\\newcommand{{\\ValRatioGone}}{{{r['dgps']['G1']['c_ratio_90_1']:.2f}}}",
         f"\\newcommand{{\\ValRatioGzero}}{{{_fmt(r['dgps']['G0']['c_ratio_90_1'], 2)}}}",
         f"\\newcommand{{\\ValRatioGthree}}{{{r['dgps']['G3']['c_ratio_90_1']:.2f}}}"]
    (GEN / "validation_macros.tex").write_text("\n".join(m) + "\n")


def build_solvency(recompute: bool) -> None:
    path = PROV / "solvency_feedback.json"
    if recompute or not path.exists():
        from simulations.feedback_dealer import run

        run()
    r = json.loads(path.read_text())
    cells = {(c["S"], c["L"], c["phi"], c["mode"]): c for c in r["cells"]}
    panels = [(10.0, 0.05), (10.0, 0.10), (20.0, 0.05)]
    lines = [_header("results/provenance/solvency_feedback.json"),
             r"\begin{tabular}{rrrllll}\toprule",
             r"$S$ & $\mathrm{var}(f)$ & LRV$(f)$ & Feedback & B1 (var) & B2 (var, AC1) & B3 (var, LRV)\\\midrule"]
    for L, phi in panels:
        lines.append(f"\\multicolumn{{7}}{{l}}{{\\textit{{Leverage limit $L={L:.0f}$, inventory control $\\phi={phi:.2f}$}}}}\\\\")
        for S in r["S_grid"]:
            m = r["moments"][str(S)]
            row = [f"{S:.2f}", f"{m['var']:.2f}", f"{m['lrv']:.1f}"]
            for mode in ("feedback", "B1", "B2", "B3"):
                c = cells[(S, L, phi, mode)]
                row.append(f"{100 * c['rate']:.1f}\\% [{100 * c['ci95_exact'][0]:.1f}, {100 * c['ci95_exact'][1]:.1f}]")
            lines.append(" & ".join(row) + "\\\\")
    lines += [r"\bottomrule\end{tabular}"]
    (GEN / "solvency_feedback.tex").write_text("\n".join(lines) + "\n")
    n = r["cells"][0]["n"]
    pct = lambda S, mode, L=10.0, phi=0.05: f"{100 * cells[(S, L, phi, mode)]['rate']:.0f}"
    m = [_header("results/provenance/solvency_feedback.json"),
         f"\\newcommand{{\\SolvFbLow}}{{{pct(0.5, 'feedback')}}}",
         f"\\newcommand{{\\SolvFbHigh}}{{{pct(0.8, 'feedback')}}}",
         f"\\newcommand{{\\SolvBoneHigh}}{{{pct(0.8, 'B1')}}}",
         f"\\newcommand{{\\SolvBtwoHigh}}{{{pct(0.8, 'B2')}}}",
         f"\\newcommand{{\\SolvBthreeHigh}}{{{pct(0.8, 'B3')}}}",
         f"\\newcommand{{\\SolvSeeds}}{{{n}}}",
         f"\\newcommand{{\\SolvT}}{{{r['params']['T']}}}"]
    (GEN / "solvency_macros.tex").write_text("\n".join(m) + "\n")


def build_binance_panel(recompute: bool) -> None:
    path = PROV / "binance_panel_results.json"
    if path.exists():
        from empirical_pipeline.summarize_panel import summarize_panel
        summarize_panel()


BUILDERS = {
    "empirical": build_empirical,
    "validation": build_validation,
    "solvency": build_solvency,
    "panel": build_binance_panel,
}


def main(argv=None):
    argv = argv or sys.argv[1:]
    recompute = "--recompute" in argv
    only = [a for a in argv if not a.startswith("--")]
    GEN.mkdir(parents=True, exist_ok=True)
    for name, fn in BUILDERS.items():
        if only and name not in only:
            continue
        print(f"[build_results] {name}")
        fn(recompute)


if __name__ == "__main__":
    main()
