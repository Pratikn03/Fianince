"""Write the B3v2 table rows as a macro (multiagent_v2_table.tex) from R_multiagent_v2.json; --check compares."""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def fmt(x, d=2):
    return "---" if x is None else f"{x:.{d}f}"


def table():
    r = json.loads((HERE / "R_multiagent_v2.json").read_text())
    rows = []
    for regime, label in (("adversarial", "Adversarial"), ("random", "Random")):
        for g in ("0.001", "0.003", "0.01", "0.03"):
            c = r["by_cell"][f"{regime}|{g}"]
            rows.append(f"{label} & ${float(g):.3f}$ & ${c['T_valid']}$ & {c['crossed']}/{c['runs']} & "
                        f"{fmt(c['median_cross_over_Tvalid'])} & {c['breached']}/{c['runs']} & "
                        f"{fmt(c['median_breach_over_Tvalid'])} & {fmt(c['median_conservativeness'], 1)}\\\\")
    return ("% generated by export_multiagent_v2_table.py; do not edit\n\\newcommand{\\MAvTwoTableRows}{%\n"
            + "\n".join(rows) + "}\n")


if __name__ == "__main__":
    out = HERE / "multiagent_v2_table.tex"
    if "--check" in sys.argv:
        assert out.read_text() == table(), "B3v2 table differs from the result file"
        print("B3v2 table check: PASS")
    else:
        out.write_text(table())
