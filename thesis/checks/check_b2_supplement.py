"""Post hoc B2 sensitivity and provenance checks; never opens or reruns the registered test."""
import argparse
import hashlib
import json
from collections import defaultdict
from pathlib import Path

from scipy.stats import beta, binomtest

HERE = Path(__file__).resolve().parent
RESULT = HERE.parent / "evidence/B2_results.json"


def compute():
    result = json.loads(RESULT.read_text())
    twins = {(r["scenario"], r["seed"]): r for r in result["twins"]}
    delays = defaultdict(list)
    for run in result["runs"]:
        if run["scenario"] in ("fast", "slow"):
            twin = twins[run["scenario"], run["seed"]]
            day = lambda r: r["crisis"] if r["crisis"] is not None else 120
            delays[run["seed"]].append(day(run) - day(twin))
    assert len(delays) == 15 and all(len(v) == 2 for v in delays.values())
    means = {str(seed): sum(v) / len(v) for seed, v in sorted(delays.items())}
    pos = sum(v > 0 for v in means.values())
    neg = sum(v < 0 for v in means.values())
    controls = result["evaluation"]["n_control"]
    alarms = result["evaluation"]["P1"]["false_alarms"]
    lower = float(beta.ppf(0.025, alarms, controls - alarms + 1)) if alarms else 0.0
    upper = float(beta.ppf(0.975, alarms + 1, controls - alarms)) if alarms < controls else 1.0
    return {
        "kind": "POST_HOC_SENSITIVITY_NOT_A_REGISTERED_PRIMARY",
        "input_sha256": hashlib.sha256(RESULT.read_bytes()).hexdigest(),
        "seed_mean_delay_days": means,
        "positive_seeds": pos, "negative_seeds": neg, "tied_seeds": len(means) - pos - neg,
        "unadjusted_seed_sign_p": float(binomtest(pos, pos + neg, 0.5, alternative="greater").pvalue),
        "false_alarm_exact_95_ci": [lower, upper],
        "model_snapshot": result["meta"].get("model_snapshot"),
        "exact_model_revision_recoverable_from_result": bool(result["meta"].get("model_snapshot")),
        "limits": [
            "Seed-level aggregation is post hoc and does not replace B2's registered paired analysis.",
            "Fast and slow markets share the same seed; this check aggregates their delays before a sign test.",
            "The false-alarm interval assumes independent controls; zero observed alarms is not a zero population rate.",
            "Statistics reproduce from saved summaries; original model calls were not replayed.",
            "A current model revision cannot establish which revision produced the archived run.",
        ],
    }


def tex(r):
    return ("% post hoc B2 sensitivity, generated by check_b2_supplement.py\n"
            f"\\newcommand{{\\BtwoSeedPositive}}{{{r['positive_seeds']}}}\n"
            f"\\newcommand{{\\BtwoSeedCount}}{{{len(r['seed_mean_delay_days'])}}}\n"
            f"\\newcommand{{\\BtwoSeedP}}{{{r['unadjusted_seed_sign_p']:.6f}}}\n"
            f"\\newcommand{{\\BtwoFAUpper}}{{{100 * r['false_alarm_exact_95_ci'][1]:.1f}}}\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    result = compute()
    path = HERE / "B2_supplement.json"
    tex_path = HERE / "B2_supplement.tex"
    if args.check:
        stored = json.loads(path.read_text())
        assert stored.keys() == result.keys()
        for key in result:
            if key == "false_alarm_exact_95_ci":
                assert all(abs(a - b) < 1e-12 for a, b in zip(stored[key], result[key]))
            elif key == "unadjusted_seed_sign_p":
                assert abs(stored[key] - result[key]) < 1e-12
            else:
                assert stored[key] == result[key], key
        assert tex_path.read_text() == tex(result)
    else:
        path.write_text(json.dumps(result, indent=2) + "\n")
        tex_path.write_text(tex(result))
    print("B2 post hoc seed sensitivity and provenance: PASS (registered results unchanged)")


if __name__ == "__main__":
    main()
