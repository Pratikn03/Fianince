"""Explicit constants of Theorem thm:philog (formulas) and the computed ratios from R_modulus.json.

Writes philog_constants.tex; --check compares with the committed file."""
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
B = 1.0


def constants(rbar):
    rho = (1 + math.sqrt(1 - rbar)) ** 2 / rbar
    K = 8 * math.log(6) * math.sqrt(1 - rbar) * math.log(rho)
    return min(B, (2 * K) ** -0.5), 1 / math.sqrt(math.log(1 / rbar))


def observed(rbar):
    d = json.loads((HERE / "R_modulus.json").read_text())
    return d["check"]["growth"][f"total_feedback_Phi@{rbar}"]["omega_over_delta_sqrtlog"][-1]


def upper_bound_holds():
    """omega_L(delta) <= delta sqrt(1 + log(1/delta)/log(1/rbar)) + B delta/(1 - rbar) on every stored Phi bracket."""
    d = json.loads((HERE / "R_modulus.json").read_text())
    ok = []
    for b in d["check"]["brackets"]:
        if b["question"] == "total_feedback_Phi" and b["delta"] <= math.exp(-1):
            r, dl = b["rbar"], b["delta"]
            bound = dl * math.sqrt(1 + math.log(1 / dl) / math.log(1 / r)) + B * dl / (1 - r)
            ok.append(b["omega_lower"] <= bound)
    return len(ok) > 0 and all(ok)


def tex():
    assert upper_bound_holds(), "explicit upper bound of thm:philog violated by a computed bracket"
    lo_a, up_a = constants(0.5); lo_b, up_b = constants(0.9)
    ob_a, ob_b = observed(0.5), observed(0.9)
    assert lo_a <= ob_a <= up_a + 0.05 and lo_b <= ob_b <= up_b + 0.05
    return ("% generated by export_philog_constants.py; do not edit\n"
            f"\\newcommand{{\\PhilogLowA}}{{{lo_a:.2f}}}\\newcommand{{\\PhilogUpA}}{{{up_a:.2f}}}"
            f"\\newcommand{{\\PhilogObsA}}{{{ob_a:.2f}}}\n"
            f"\\newcommand{{\\PhilogLowB}}{{{lo_b:.2f}}}\\newcommand{{\\PhilogUpB}}{{{up_b:.2f}}}"
            f"\\newcommand{{\\PhilogObsB}}{{{ob_b:.2f}}}\n")


if __name__ == "__main__":
    out = HERE / "philog_constants.tex"
    if "--check" in sys.argv:
        assert out.read_text() == tex(), "philog constants differ"
        print("Theorem thm:philog constants: PASS")
    else:
        out.write_text(tex())
        print(out.read_text())
