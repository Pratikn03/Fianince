"""Numbers of Test B2 printed in the AI chapter beyond the registered macros (B2_numbers.tex), computed from the
registered result file. Writes checks/B2_extra.tex; the verifier regenerates and compares it. Descriptive only: no
test is added or changed here."""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "evidence"))


def numbers_tex(r):
    import b2_llm as B
    e, s = r["evaluation"], r["evaluation"]["secondary"]
    tw = [t for t in r["twins"] if t["scenario"] in ("fast", "slow") and t["crisis"] is not None]
    twin_lead = float(np.median([B.L.B.lead(t, "std", "t2z") for t in tw]))
    sw = s["vendor_first_switch_day"]
    fin = [x for x in s["vendor_final_stance"] if x is not None]
    lines = ["% generated by b2_extra_numbers.py from evidence/B2_results.json; do not edit",
             "\\newcommand{\\BtwoLeadFast}{%.1f}\\newcommand{\\BtwoLeadSlow}{%.1f}\\newcommand{\\BtwoTwinLead}{%.1f}" % (
                 s["median_leads"]["fast_std_t2z"], s["median_leads"]["slow_std_t2z"], twin_lead),
             "\\newcommand{\\BtwoDiscTtzFA}{%d}\\newcommand{\\BtwoDiscLostFA}{%d}" % (
                 s["false_alarms_controls"]["disc_t2z"], s["false_alarms_controls"]["disc_lost"]),
             "\\newcommand{\\BtwoSwitchMin}{%d}\\newcommand{\\BtwoSwitchMax}{%d}\\newcommand{\\BtwoFinalMin}{%d}\\newcommand{\\BtwoFinalMax}{%d}" % (
                 min(sw), max(sw), min(fin), max(fin)),
             "\\newcommand{\\BtwoLossCut}{%.2f}\\newcommand{\\BtwoChangeRate}{%.1f}" % (
                 -s["desk_abs_change_after_loss"], 100 * s["desk_stance_change_rate"]),
             "\\newcommand{\\BtwoShare}{%.2f}\\newcommand{\\BtwoStatic}{%.2f}\\newcommand{\\BtwoTwinsAbove}{%d}\\newcommand{\\BtwoTwinsBelow}{%d}" % (
                 s["share_vs_static"]["median_share"], s["share_vs_static"]["median_static"],
                 s["twins_share_vs_static"]["above"], s["twins_share_vs_static"]["below"]),
             "\\newcommand{\\BtwoMaxDelay}{%d}\\newcommand{\\BtwoHours}{%.1f}" % (
                 max(e["P3"]["delays"]), r["meta"]["seconds_model"] / 3600)]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    res = json.loads((ROOT / "evidence/B2_results.json").read_text())
    (ROOT / "checks/B2_extra.tex").write_text(numbers_tex(res))
    print(numbers_tex(res))
