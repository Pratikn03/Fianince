"""Numbers for Chapter 5 that the four test pipelines do not write themselves, and the exploratory pilot.

Reads the committed result files (E1v2, D1, G1, V1 and the exploratory pilot) and writes results_extra.tex.
`--check` recomputes and compares with the committed file (used by verify_thesis_numbers.py).
"""
import argparse
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
EV = HERE.parent / "evidence"
OUT = HERE / "results_extra.tex"


def f(x, d=2, sign=False):
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    return s.replace("-", "$-$") if not sign else s.replace("-", "$-$").replace("+", "$+$")


def build():
    L = ["% generated by export_results_extra.py from the committed result files; do not edit"]
    # E1v2: how many price-only rate intervals reach the bounds of the fit, how many I_id are capped near 1
    e = json.loads((EV / "E1v2_results.json").read_text())
    sat = small = 0
    for v in e["per_symbol"].values():
        if "price_only" not in v:
            continue
        po = v["price_only"]
        if any(x <= 0.005 or x >= 0.985 for x in po["r_fast_ci"] + po["r_slow_ci"]):
            sat += 1
        if v["I_id"] < 2.5:
            small += 1
    L += [f"\\newcommand{{\\EoneSaturated}}{{{sat}}}", f"\\newcommand{{\\EoneSmallIid}}{{{small}}}",
          f"\\newcommand{{\\EonePholmOne}}{{{e['evaluation']['p_holm'][0]:.2f}}}"]
    # D1
    d = json.loads((EV / "D1_results.json").read_text())["evaluation"]
    L += [f"\\newcommand{{\\DonePholmOne}}{{{d['p_holm'][0]:.3f}}}", f"\\newcommand{{\\DonePholmTwo}}{{{d['p_holm'][1]:.3f}}}"]
    # G1
    g = json.loads((EV / "G1_results.json").read_text())
    g = g.get("evaluation", g)
    st, al = g["stress"], g["all_hours"]
    L += [f"\\newcommand{{\\GoneTheta}}{{{g['theta']:g}}}",
          f"\\newcommand{{\\GoneThetaTLRzero}}{{{g['theta_training_TLR']['0.0']:.0f}}}",
          f"\\newcommand{{\\GoneThetaTLRone}}{{{g['theta_training_TLR']['1.0']:.0f}}}",
          f"\\newcommand{{\\GoneStressGuard}}{{{f(st['guard']['log_TLR_minus_vol'], 3, True)}}}",
          f"\\newcommand{{\\GoneStressGuardCI}}{{[{f(st['guard']['ci'][0], 2)},{f(st['guard']['ci'][1], 2)}]}}",
          f"\\newcommand{{\\GoneStressP}}{{{st['guard']['p_one_sided']:.2f}}}",
          f"\\newcommand{{\\GoneStressDates}}{{{st['n_dates']}}}",
          f"\\newcommand{{\\GoneAllGuard}}{{{f(al['guard']['log_TLR_minus_vol'], 2, True)}}}",
          f"\\newcommand{{\\GoneAllGuardCI}}{{[{f(al['guard']['ci'][0], 2)},{f(al['guard']['ci'][1], 2)}]}}",
          f"\\newcommand{{\\GoneAllHours}}{{{al['n_hours']:,}}}".replace(",", "{,}"),
          f"\\newcommand{{\\GoneAllRatio}}{{{np.exp(al['guard']['log_TLR_minus_vol']):.2f}}}"]
    # V1
    v = json.loads((EV / "V1_results.json").read_text()); ve = v["evaluation"]
    L += [f"\\newcommand{{\\VonePairs}}{{{len(v['pairs'])}}}", f"\\newcommand{{\\VoneIncluded}}{{{len(v['included'])}}}",
          f"\\newcommand{{\\VoneCWp}}{{{ve['clark_west_p']:.2f}}}",
          f"\\newcommand{{\\VoneDRtwoCI}}{{[{f(100 * ve['delta_r2_ci'][0], 2)},{f(100 * ve['delta_r2_ci'][1], 2)}]}}",
          f"\\newcommand{{\\VoneTestHours}}{{{ve['n_test']:,}}}".replace(",", "{,}")]
    # exploratory pilot
    p = json.loads((EV / "pilot_after_e1v2_results.json").read_text())
    s = p["summary"]; rows = [r for r in p["per_symbol"].values() if "full" in r]
    same = sum(r["full"]["M_x_12"]["sign"] == r["full"]["M_nofb_12"]["sign"] for r in rows)
    ratio = np.median([abs(r["full"]["kappa_12"]["point"] * r["full"]["Phi_x_12"]["point"] / r["full"]["beta_12"]["point"]) for r in rows])
    neg = sum(r["full"]["kappa_12"]["point"] * r["full"]["Phi_x_12"]["point"] < 0 for r in rows)
    L += [f"\\newcommand{{\\PilotSymbols}}{{{s['n_symbols']}}}",
          f"\\newcommand{{\\PilotMarginX}}{{{s['decided_M_x_12']}}}", f"\\newcommand{{\\PilotMarginXsafe}}{{{s['safe_M_x_12']}}}",
          f"\\newcommand{{\\PilotMarginRet}}{{{s['decided_M_ret_12']}}}", f"\\newcommand{{\\PilotNoFb}}{{{s['decided_M_nofb_12']}}}",
          f"\\newcommand{{\\PilotSame}}{{{same}}}", f"\\newcommand{{\\PilotFbRatio}}{{{ratio:.2f}}}", f"\\newcommand{{\\PilotFbNeg}}{{{neg}}}",
          f"\\newcommand{{\\PilotIdentified}}{{{s['identified']}}}", f"\\newcommand{{\\PilotSaturated}}{{{s['saturated']}}}",
          f"\\newcommand{{\\PilotCurveTen}}{{{s['curve']['10']['M_x_12_decided']}}}",
          f"\\newcommand{{\\PilotCurveTwenty}}{{{s['curve']['20']['M_x_12_decided']}}}",
          f"\\newcommand{{\\PilotCurveForty}}{{{s['curve']['40']['M_x_12_decided']}}}",
          f"\\newcommand{{\\PilotIdMax}}{{{max(s['curve'][k]['identified'] for k in s['curve'])}}}",
          f"\\newcommand{{\\PilotDrift}}{{{s['stationarity_p_below_05']}}}",
          f"\\newcommand{{\\PilotWithinSlope}}{{{f(s['median_slopes']['within_quarter_mean'], 2)}}}",
          f"\\newcommand{{\\PilotWithinIn}}{{{s['within_slope_in_P1_range']}}}",
          f"\\newcommand{{\\PilotAcrossIn}}{{{s['across_slope_in_P1_range']}}}"]
    # Pilot 2 (every one-minute BTC move as a shock; exploratory)
    q = json.loads((EV / "pilot2_natural_experiments_results.json").read_text())["summary"]
    L += [f"\\newcommand{{\\PtwoPassThrough}}{{{100 * q['median_pass_through_0']:.0f}}}",
          f"\\newcommand{{\\PtwoPreOK}}{{{q['placebo_pre_ci_covers_0']}}}",
          f"\\newcommand{{\\PtwoReverseOK}}{{{q['placebo_reverse_ci_covers_0']}}}"]
    # Pilot 2b (scheduled US macro releases at one second; exploratory)
    b2 = json.loads((EV / "pilot2b_announcements_results.json").read_text())
    sb, per = b2["summary"], list(b2["per_symbol"].values())
    a120 = [v["A"]["120"] for v in per]
    L += [f"\\newcommand{{\\PtwobEvents}}{{{len(b2['events'])}}}", f"\\newcommand{{\\PtwobSymbols}}{{{sb['n_symbols']}}}",
          f"\\newcommand{{\\PtwobShare}}{{{100 * sb['median_p0']:.0f}}}", f"\\newcommand{{\\PtwobBeta}}{{{sb['median_beta']:.2f}}}",
          f"\\newcommand{{\\PtwobPreOK}}{{{sb['placebo_pre_covers_zero']}}}",
          f"\\newcommand{{\\PtwobPreSize}}{{{100 * sb['median_abs_pre_over_beta']:.1f}}}",
          f"\\newcommand{{\\PtwobPseudo}}{{{100 * sb['median_pseudo_shock_sd_ratio']:.0f}}}",
          f"\\newcommand{{\\PtwobNegArea}}{{{sb['overshoot_A120_negative']}}}",
          f"\\newcommand{{\\PtwobNegAreaSig}}{{{sum(x['ci'][1] < 0 for x in a120)}}}",
          f"\\newcommand{{\\PtwobOneSided}}{{{sb['certified_A120_below_60s']}}}",
          f"\\newcommand{{\\PtwobTwoSided}}{{{sum(-60 < x['ci'][0] and x['ci'][1] < 60 for x in a120)}}}",
          f"\\newcommand{{\\PtwobPosArea}}{{{sum(x['point'] > 0 for x in a120)}}}",
          f"\\newcommand{{\\PtwobIdentified}}{{{sb['identified']}}}",
          f"\\newcommand{{\\PtwobSlope}}{{{f(sb['median_width_slope'], 2)}}}",
          f"\\newcommand{{\\PtwobNegTotal}}{{{sum(v['A_inf'] < 0 for v in per)}}}",
          f"\\newcommand{{\\PtwobNegTotalSig}}{{{sum(v['A_inf_ci'][1] < 0 for v in per)}}}"]
    # Pilot 3 (horizon-matched price-only versus tagged half-lives; exploratory; transcribed Colab printout)
    t3 = json.loads((EV / "pilot3_horizon_matched_results.json").read_text())
    s3, rows3 = t3["summary"], t3["per_symbol"]
    L += [f"\\newcommand{{\\PthreeTagHL}}{{{s3['median_tagged_half_life_h']:.1f}}}",
          f"\\newcommand{{\\PthreeTagWidth}}{{{10 ** s3['median_tagged_width_log10']:.1f}}}",
          f"\\newcommand{{\\PthreeHLtwelve}}{{{60 * s3['L12']['median_half_life_h']:.0f}}}",
          f"\\newcommand{{\\PthreeShortTwelve}}{{{sum(r['L12']['half_life_h'] < 0.5 for r in rows3)}}}",
          f"\\newcommand{{\\PthreeHLninetysix}}{{{s3['L96']['median_half_life_h']:.1f}}}",
          f"\\newcommand{{\\PthreeNearninetysix}}{{{sum(0.5 <= r['L96']['half_life_h'] / r['tagged_half_life_h'] <= 2 for r in rows3)}}}",
          f"\\newcommand{{\\PthreeRatioTwelve}}{{{s3['L12']['median_ratio_to_tagged']:.1f}}}",
          f"\\newcommand{{\\PthreeRatioFortyeight}}{{{s3['L48']['median_ratio_to_tagged']:.1f}}}",
          f"\\newcommand{{\\PthreeRatioNinetysix}}{{{s3['L96']['median_ratio_to_tagged']:.1f}}}",
          f"\\newcommand{{\\PthreeTighter}}{{{min(sum(r[k]['width_ratio_to_tagged'] > 1 for r in rows3) for k in ('L12', 'L48', 'L96'))}}}",
          f"\\newcommand{{\\PthreeMinRatio}}{{{min(r['L96']['width_ratio_to_tagged'] for r in rows3):.1f}}}",
          f"\\newcommand{{\\PthreeBoundNinetysix}}{{{s3['L96']['reaches_bound']}}}",
          f"\\newcommand{{\\PthreeBoundTwelve}}{{{s3['L12']['reaches_bound']}}}"]
    # Test C2 (registered): numbers beyond those its pipeline writes
    c2 = json.loads((EV / "C2_results.json").read_text()); ce = c2["evaluation"]; sc = ce["secondary"]
    hm = [v["horizon_matched"] for v in c2["per_symbol"].values() if v.get("horizon_matched", {}).get("evaluable")]
    tg = [t for h in hm for t in h["tagged"].values()]
    rj_ci_below = sum(np.isfinite(t.get("r_jackknife_ci", [np.nan, np.nan])[1]) and t["r_jackknife_ci"][1] < 1 for t in tg)
    L += [f"\\newcommand{{\\CtwoPholmOne}}{{{ce['p_holm'][0]:.3f}}}",
          "\\newcommand{\\CtwoPtwoP}{%s\\times10^{%d}}" % (f"{ce['p_holm'][1]:.0e}".split("e")[0], int(f"{ce['p_holm'][1]:.0e}".split("e")[1])),
          "\\newcommand{\\CtwoPthreeP}{%s\\times10^{%d}}" % (f"{ce['p_holm'][2]:.0e}".split("e")[0], int(f"{ce['p_holm'][2]:.0e}".split("e")[1])),
          f"\\newcommand{{\\CtwoSafe}}{{{sc['safe']}}}", f"\\newcommand{{\\CtwoUnsafe}}{{{sc['unsafe']}}}",
          f"\\newcommand{{\\CtwoSameNoFb}}{{{sc['same_decision_without_feedback']}}}",
          f"\\newcommand{{\\CtwoFbNeg}}{{{sc['feedback_negative']}}}",
          f"\\newcommand{{\\CtwoRatio}}{{{sc['P3_median_width_ratio']:.1f}}}",
          f"\\newcommand{{\\CtwoMinRatio}}{{{min(h['width_ratio'] for h in hm):.1f}}}",
          f"\\newcommand{{\\CtwoBound}}{{{sc['P3_price_only_reaches_bound']}}}",
          f"\\newcommand{{\\CtwoPOhl}}{{{sc['P3_median_price_only_half_life_h']:.1f}}}",
          f"\\newcommand{{\\CtwoTagR}}{{{np.nanmedian([t['r'] for t in tg]):.3f}}}",
          f"\\newcommand{{\\CtwoTagHL}}{{{np.nanmedian([t['half_life_h'] for t in tg]):.1f}}}",
          f"\\newcommand{{\\CtwoJackR}}{{{sc['P3_median_tagged_r_jackknife']:.4f}}}",
          f"\\newcommand{{\\CtwoJackBelow}}{{{rj_ci_below}}}", f"\\newcommand{{\\CtwoClassFits}}{{{len(tg)}}}"]
    # Test O1 (registered): numbers beyond those its pipeline writes
    o1 = json.loads((EV / "O1_results.json").read_text()); so = o1["secondary"]; ci120 = o1["pooled_A_ci"]["120"]
    L += [f"\\newcommand{{\\OoneCI}}{{[{ci120[0]:.0f},{ci120[1]:.0f}]}}",
          f"\\newcommand{{\\OoneNeg}}{{{so['symbols_A120_negative']}}}",
          f"\\newcommand{{\\OoneNegSig}}{{{so['symbols_A120_ci_below_zero']}}}",
          f"\\newcommand{{\\OoneTwoSided}}{{{so['symbols_two_sided_certified_60s']}}}",
          f"\\newcommand{{\\OoneShare}}{{{100 * so['median_share_at_10s']:.0f}}}",
          f"\\newcommand{{\\OoneBeta}}{{{so['median_beta']:.2f}}}",
          f"\\newcommand{{\\OoneIdentified}}{{{so['identified']}}}",
          f"\\newcommand{{\\OonePre}}{{{f(o1['validity']['V1_pooled_pre_over_beta'], 3)}}}",
          f"\\newcommand{{\\OonePreCI}}{{[{f(o1['validity']['V1_ci'][0], 2)},{f(o1['validity']['V1_ci'][1], 2)}]}}",
          f"\\newcommand{{\\OonePseudo}}{{{100 * o1['validity']['V2_median_pseudo_shock_sd_ratio']:.0f}}}"]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    t = build()
    if a.check:
        assert OUT.read_text() == t, "results_extra.tex differs from the result files"
        print("Chapter 5 extra numbers: PASS")
    else:
        OUT.write_text(t); print(t)
